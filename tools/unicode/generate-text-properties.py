#!/usr/bin/env python3
"""Generate the Unicode 16.0 text tables (the version used by our HarfBuzz).

Download from https://www.unicode.org/Public/16.0.0/ucd/:
  auxiliary/GraphemeBreakProperty.txt, emoji/emoji-data.txt,
  emoji/emoji-variation-sequences.txt, DerivedCoreProperties.txt
Usage: generate-text-properties.py INPUT_DIRECTORY OUTPUT_HEADER
"""

import pathlib
import sys

source, destination = map(pathlib.Path, sys.argv[1:])
properties = [0] * 0x110000
gcb = dict(zip(["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator",
                "Prepend", "SpacingMark", "L", "V", "T"], range(12)))
bits = {"Emoji": 16, "Emoji_Presentation": 32, "Extended_Pictographic": 64,
        "InCB; Consonant": 128, "InCB; Linker": 256, "InCB; Extend": 512,
        "Default_Ignorable_Code_Point": 1024, "Emoji_Modifier": 4096}
for name in ["GraphemeBreakProperty.txt", "emoji-data.txt", "DerivedCoreProperties.txt"]:
    for line in (source / name).read_text().splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        span, prop = [s.strip() for s in line.split(";", 1)]
        prop = "; ".join(s.strip() for s in prop.split(";"))
        value = gcb.get(prop, 0) if name.startswith("Grapheme") else bits.get(prop, 0)
        # Hangul LV/LVT syllables are classified algorithmically.
        if not value:
            continue
        ends = span.split("..")
        start, end = int(ends[0], 16), int(ends[-1], 16)
        for codepoint in range(start, end + 1):
            properties[codepoint] |= value

for line in (source / "emoji-variation-sequences.txt").read_text().splitlines():
    sequence = line.split("#")[0].split(";")[0].strip()
    if sequence:
        properties[int(sequence.split()[0], 16)] |= 2048

lines = ["// Generated by tools/unicode/generate-text-properties.py. Do not edit.",
         "// Unicode 16.0.0, Copyright © 2024 Unicode, Inc.",
         "// Distributed under https://www.unicode.org/license.txt", "",
         "static constexpr UnicodeRange TextPropertyRanges[] = {"]
start = 0
for end in range(1, len(properties) + 1):
    if end == len(properties) or properties[end] != properties[start]:
        if properties[start]:
            lines.append(f"    {{0x{start:X}, 0x{end - 1:X}, {properties[start]}}},")
        start = end
lines.append("};\n")
destination.write_text("\n".join(lines))
