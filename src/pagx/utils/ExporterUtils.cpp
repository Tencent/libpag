FillStrokeInfo CollectFillStroke(const std::vector<Element*>& contents) {
  FillStrokeInfo info = {};
  for (const auto* element : contents) {
    if (element->nodeType() == NodeType::Fill && !info.fill) {
      info.fill = static_cast<const Fill*>(element);
    } else if (element->nodeType() == NodeType::Stroke && !info.stroke) {
      info.stroke = static_cast<const Stroke*>(element);
    } else if (element->nodeType() == NodeType::TextBox && !info.textBox) {
      info.textBox = static_cast<const TextBox*>(element);
    }
    if (info.fill && info.stroke && info.textBox) {
      break;
    }
  }
  return info;
}

bool HasForegroundPainter(const std::vector<Element*>& contents) {
  for (const auto* element : contents) {
    auto type = element->nodeType();
    if (type == NodeType::Fill) {
      if (static_cast<const Fill*>(element)->placement == LayerPlacement::Foreground) {
        return true;
      }
    } else if (type == NodeType::Stroke) {
      if (static_cast<const Stroke*>(element)->placement == LayerPlacement::Foreground) {
        return true;
      }
    } else if (type == NodeType::TextBox) {
      // TextBox derives from Group; check its child elements before treating it as a leaf.
      auto* tb = static_cast<const TextBox*>(element);
      if (HasForegroundPainter(tb->elements)) {
        return true;
      }
    } else if (type == NodeType::Group) {
      auto* group = static_cast<const Group*>(element);
      if (HasForegroundPainter(group->elements)) {
        return true;
      }
    }
  }
  return false;
}

std::string EscapeCssFontFamily(const std::string& family) {
  std::string out;
  out.reserve(family.size());
  for (char c : family) {
    // Drop control characters (including NUL, \n, \r, \t) and the characters that would let an
    // attacker escape the single-quoted font-family value into the surrounding CSS context.
    auto uc = static_cast<unsigned char>(c);
    if (uc < 0x20 || c == ';' || c == '}' || c == '{' || c == '<' || c == '>') {
      continue;
    }
    if (c == '\\' || c == '\'') {
      out += '\\';
    }
    out += c;
  }
  return out;
}

Matrix BuildLayerMatrix(const Layer* layer, const LayerChannelOverride* override) {
  // Local transform priority: matrix3D > matrix > x / y / z and the transform components. The
  // position generated by constraints or container layout stays outside the local transform:
  // T(layout) * local. A 3D local transform is reduced to the 2D affine acting on the z=0 plane.
  // When its w row does not depend on x or y (for example a perspective combined with a Z
  // translation), w is the constant [3][3] value and the affine is divided by it, which is exact.
  // Otherwise (an X or Y rotation under perspective) no exact affine exists, and the x / y rows are
  // kept without the divide. The layout translation is added afterwards, so it only shifts the
  // projected translation.
  //
  // `override` only substitutes the authored 2D matrix: this exporter's transform model has no
  // rotation / scale / skew / anchor components, so those channels are reported as unsupported by
  // SVGAnimationPlan rather than being silently ignored here.
  auto layoutPosition = layer->layoutPosition();
  float layoutX = std::isnan(layoutPosition.x) ? 0 : layoutPosition.x;
  float layoutY = std::isnan(layoutPosition.y) ? 0 : layoutPosition.y;
  // A non-finite matrix is ignored by the renderer (see BuildLayerTransform3DWithAnchor), so it is treated
  // as if it were not set here as well; the same flags also skip an identity matrix.
  bool hasMatrix3D = !layer->matrix3D.isIdentity() && IsFiniteMatrix3D(layer->matrix3D);
  const Matrix& authored =
      override != nullptr && override->matrix != nullptr ? *override->matrix : layer->matrix;
  bool hasMatrix = !authored.isIdentity() && IsFiniteMatrix(authored);
  // An anchor makes the plain 2D matrix branch wrong: the pivot must still be folded in, so route
  // it through BuildLayerTransform3DWithAnchor as well.
  bool hasAnchor = layer->anchor.x != 0 || layer->anchor.y != 0 || layer->anchorZ != 0;
  Matrix m = hasMatrix ? authored : Matrix::Identity();
  if (hasMatrix3D || hasAnchor || (!hasMatrix && HasLayerTransformComponents(layer))) {
    auto local = BuildLayerTransform3DWithAnchor(layer);
    const float* v = local.values;
    float w = 1.0f;
    if (v[3] == 0 && v[7] == 0 && std::isfinite(v[15]) && v[15] != 0) {
      w = v[15];
    }
    m.a = v[0] / w;
    m.b = v[1] / w;
    m.c = v[4] / w;
    m.d = v[5] / w;
    m.tx = v[12] / w;
    m.ty = v[13] / w;
  } else if (!hasMatrix) {
    m.tx += layer->x;
    m.ty += layer->y;
  }
  m.tx += layoutX;
  m.ty += layoutY;
  return m;
}

Matrix BuildGroupMatrix(const Group* group, const GroupChannelOverride* override) {
  // The authored `position` attribute is a layout input only; the actual
  // rendered translation comes from renderPosition() after constraints,
  // padding, and flex allocation have been resolved. anchor, rotation,
  // scale, and skew are not layout-owned and are read directly.
  auto renderPos = group->renderPosition();
  auto anchor =
      override != nullptr && override->anchor != nullptr ? *override->anchor : group->anchor;
  auto scale = group->scale;
  if (override != nullptr && override->scaleX != nullptr) {
    scale.x = *override->scaleX;
  }
  if (override != nullptr && override->scaleY != nullptr) {
    scale.y = *override->scaleY;
  }
  float rotation =
      override != nullptr && override->rotation != nullptr ? *override->rotation : group->rotation;
  float skew = override != nullptr && override->skew != nullptr ? *override->skew : group->skew;
  float skewAxis =
      override != nullptr && override->skewAxis != nullptr ? *override->skewAxis : group->skewAxis;
  bool hasAnchor = !FloatNearlyZero(anchor.x) || !FloatNearlyZero(anchor.y);
  // An animated position must count even when the authored one is zero, otherwise the early-out
  // below returns an empty matrix and the track never moves.
  bool hasPosition = !FloatNearlyZero(renderPos.x) || !FloatNearlyZero(renderPos.y) ||
                     (override != nullptr && override->position != nullptr);
  bool hasRotation = !FloatNearlyZero(rotation);
  bool hasScale = !FloatNearlyZero(scale.x - 1.0f) || !FloatNearlyZero(scale.y - 1.0f);
  bool hasSkew = !FloatNearlyZero(skew);

  if (!hasAnchor && !hasPosition && !hasRotation && !hasScale && !hasSkew) {
    return {};
  }

  Matrix m = {};
  if (hasAnchor) {
    m = Matrix::Translate(-anchor.x, -anchor.y);
  }
  if (hasScale) {
    m = Matrix::Scale(scale.x, scale.y) * m;
  }
  if (hasSkew) {
    // Sign matches the native renderer (ShapeRenderer::SkewFromAxis passes
    // DegreesToRadians(-skew)). Keeping a single convention across native, SVG,
    // PPT, and HTML exporters avoids per-pipeline sign flips.
    m = Matrix::Rotate(skewAxis) * m;
    Matrix shear = {};
    shear.c = std::tan(pag::DegreesToRadians(-skew));
    m = shear * m;
    m = Matrix::Rotate(-skewAxis) * m;
  }
  if (hasRotation) {
    m = Matrix::Rotate(rotation) * m;
  }
  if (!FloatNearlyZero(renderPos.x) || !FloatNearlyZero(renderPos.y) ||
      (override != nullptr && override->position != nullptr)) {
    Point position =
        override != nullptr && override->position != nullptr ? *override->position : renderPos;
    m = Matrix::Translate(position.x, position.y) * m;
  }

  return m;
}

FillRule DetectMaskFillRule(const Layer* maskLayer) {
  for (const auto* element : maskLayer->contents) {
    if (element->nodeType() == NodeType::Fill) {
      auto rule = static_cast<const Fill*>(element)->fillRule;
      if (rule == FillRule::EvenOdd) {
        return FillRule::EvenOdd;
      }
    }
  }
  for (const auto* child : maskLayer->children) {
    if (DetectMaskFillRule(child) == FillRule::EvenOdd) {
      return FillRule::EvenOdd;
    }
  }
  return FillRule::Winding;
}

void DecomposeScale(const Matrix& m, float* sx, float* sy) {
  *sx = std::sqrt(m.a * m.a + m.b * m.b);
  float det = m.a * m.d - m.b * m.c;
  *sy = (*sx > 0) ? std::abs(det) / *sx : 0;
}

